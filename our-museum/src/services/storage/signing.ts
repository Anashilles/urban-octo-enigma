import { createHmac, timingSafeEqual } from "node:crypto";

/**
 * HMAC signatures for local-storage URLs. Expiry times are rounded up to a
 * time bucket so the same object keeps the same URL for a few minutes, letting
 * the browser cache images instead of re-downloading them on every refresh.
 */
export const URL_BUCKET_SECONDS = 300;

export function bucketedExpiry(nowSeconds: number, expiresInSeconds: number, bucket = URL_BUCKET_SECONDS): number {
  return Math.ceil((nowSeconds + expiresInSeconds) / bucket) * bucket;
}

export function sign(secret: string, parts: Array<string | number>): string {
  return createHmac("sha256", secret).update(parts.join("\n")).digest("base64url");
}

export function verify(secret: string, parts: Array<string | number>, signature: string | null | undefined): boolean {
  if (!signature) return false;
  const expected = Buffer.from(sign(secret, parts));
  const given = Buffer.from(signature);
  return expected.length === given.length && timingSafeEqual(expected, given);
}

/** Storage keys are generated by the server; this guards against traversal anyway. */
export function assertSafeKey(key: string): string {
  if (!/^[a-zA-Z0-9][a-zA-Z0-9/_.-]{0,255}$/.test(key) || key.includes("..") || key.includes("//")) {
    throw new Error("Invalid storage key");
  }
  return key;
}
